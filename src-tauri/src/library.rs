    /// A fresh temp folder per test, so parallel tests never share files.
    fn temp_dir(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("oer-test-{name}-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    fn write(path: &Path, bytes: &[u8]) -> String {
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::File::create(path).unwrap().write_all(bytes).unwrap();
        path.to_string_lossy().into_owned()
    }

    fn pdf(dir: &Path, name: &str) -> String {
        write(&dir.join(name), b"%PDF-1.4 test")
    }

