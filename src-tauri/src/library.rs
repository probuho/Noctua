//! Book library persisted in SQLite. Original files are never modified or
//! deleted; the library only stores references plus reading state.

use crate::error::{Error, Result};
use crate::formats;
use rusqlite::{params, Connection, OptionalExtension, Row};
use serde::Serialize;
use std::path::Path;
use std::time::{SystemTime, UNIX_EPOCH};

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Book {
    pub id: i64,
    pub path: String,
    pub format: String,
    pub title: String,
    pub author: Option<String>,
    /// Cover thumbnail as a data URL, generated by the frontend plugin.
    pub cover: Option<String>,
    pub size: i64,
    pub added_at: i64,
    pub last_opened: Option<i64>,
    /// Plugin-specific position (EPUB CFI, PDF page number, ...).
    pub location: Option<String>,
    pub progress: f64,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Bookmark {
    pub id: i64,
    pub book_id: i64,
    /// Same opaque, plugin-specific format as `Book::location`.
    pub location: String,
    pub label: String,
    pub progress: f64,
    pub created_at: i64,
}

#[derive(Debug, Default, Serialize)]
pub struct AddResult {
    pub added: Vec<Book>,
    pub duplicates: Vec<String>,
    pub unsupported: Vec<String>,
}

const COLUMNS: &str =
    "id, path, format, title, author, cover, size, added_at, last_opened, location, progress";

pub struct Library {
    conn: Connection,
}

fn now() -> i64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or_default()
}

fn row_to_book(row: &Row) -> rusqlite::Result<Book> {
    Ok(Book {
        id: row.get(0)?,
        path: row.get(1)?,
        format: row.get(2)?,
        title: row.get(3)?,
        author: row.get(4)?,
        cover: row.get(5)?,
        size: row.get(6)?,
        added_at: row.get(7)?,
        last_opened: row.get(8)?,
        location: row.get(9)?,
        progress: row.get(10)?,
    })
}

impl Library {
    pub fn open(path: &Path) -> Result<Self> {
        Self::init(Connection::open(path)?)
    }

    #[cfg(test)]
    pub fn open_in_memory() -> Result<Self> {
        Self::init(Connection::open_in_memory()?)
    }

    fn init(conn: Connection) -> Result<Self> {
        conn.execute_batch(
            "PRAGMA foreign_keys = ON;
            CREATE TABLE IF NOT EXISTS books (
                id          INTEGER PRIMARY KEY,
                path        TEXT NOT NULL UNIQUE,
                format      TEXT NOT NULL,
                title       TEXT NOT NULL,
                author      TEXT,
                cover       TEXT,
                size        INTEGER NOT NULL,
                added_at    INTEGER NOT NULL,
                last_opened INTEGER,
                location    TEXT,
                progress    REAL NOT NULL DEFAULT 0
            );
            CREATE TABLE IF NOT EXISTS bookmarks (
                id          INTEGER PRIMARY KEY,
                book_id     INTEGER NOT NULL REFERENCES books(id) ON DELETE CASCADE,
                location    TEXT NOT NULL,
                label       TEXT NOT NULL,
                progress    REAL NOT NULL,
                created_at  INTEGER NOT NULL,
                UNIQUE (book_id, location)
            );",
        )?;
        Ok(Self { conn })
    }

    pub fn list(&self) -> Result<Vec<Book>> {
        let mut stmt = self.conn.prepare(&format!(
            "SELECT {COLUMNS} FROM books ORDER BY COALESCE(last_opened, added_at) DESC"
        ))?;
        let books = stmt.query_map([], row_to_book)?.collect::<rusqlite::Result<_>>()?;
        Ok(books)
    }

    pub fn get(&self, id: i64) -> Result<Book> {
        self.conn
            .query_row(&format!("SELECT {COLUMNS} FROM books WHERE id = ?1"), [id], row_to_book)
            .optional()?
            .ok_or(Error::BookNotFound(id))
    }

    pub fn add_paths(&self, paths: &[String]) -> Result<AddResult> {
        let mut result = AddResult::default();
        for raw in paths {
            let path = Path::new(raw);
            let Some(format) = formats::detect(path) else {
                result.unsupported.push(raw.clone());
                continue;
            };
            let title = path
                .file_stem()
                .and_then(|s| s.to_str())
                .unwrap_or("Untitled")
                .to_string();
            let size = std::fs::metadata(path)?.len() as i64;
            let inserted = self.conn.execute(
                "INSERT OR IGNORE INTO books (path, format, title, size, added_at)
                 VALUES (?1, ?2, ?3, ?4, ?5)",
                params![raw, format.id, title, size, now()],
            )?;
            if inserted == 0 {
                result.duplicates.push(raw.clone());
            } else {
                result.added.push(self.get(self.conn.last_insert_rowid())?);
            }
        }
        Ok(result)
    }

    pub fn remove(&self, id: i64) -> Result<()> {
        self.conn.execute("DELETE FROM books WHERE id = ?1", [id])?;
        Ok(())
    }

    pub fn update_metadata(
        &self,
        id: i64,
        title: Option<&str>,
        author: Option<&str>,
        cover: Option<&str>,
    ) -> Result<()> {
        self.conn.execute(
            "UPDATE books SET title = COALESCE(?2, title), author = COALESCE(?3, author),
             cover = COALESCE(?4, cover) WHERE id = ?1",
            params![id, title, author, cover],
        )?;
        Ok(())
    }

    pub fn mark_opened(&self, id: i64) -> Result<()> {
        self.conn.execute("UPDATE books SET last_opened = ?2 WHERE id = ?1", params![id, now()])?;
        Ok(())
    }

    pub fn save_progress(&self, id: i64, location: &str, progress: f64) -> Result<()> {
        self.conn.execute(
            "UPDATE books SET location = ?2, progress = ?3 WHERE id = ?1",
            params![id, location, progress.clamp(0.0, 1.0)],
        )?;
        Ok(())
    }

    pub fn bookmarks(&self, book_id: i64) -> Result<Vec<Bookmark>> {
        let mut stmt = self.conn.prepare(
            "SELECT id, book_id, location, label, progress, created_at
             FROM bookmarks WHERE book_id = ?1 ORDER BY progress",
        )?;
        let rows = stmt.query_map([book_id], |row| {
            Ok(Bookmark {
                id: row.get(0)?,
                book_id: row.get(1)?,
                location: row.get(2)?,
                label: row.get(3)?,
                progress: row.get(4)?,
                created_at: row.get(5)?,
            })
        })?;
        Ok(rows.collect::<rusqlite::Result<_>>()?)
    }

    /// Adding a bookmark at an existing location just refreshes its label.
    pub fn add_bookmark(&self, book_id: i64, location: &str, label: &str, progress: f64) -> Result<()> {
        self.conn.execute(
            "INSERT INTO bookmarks (book_id, location, label, progress, created_at)
             VALUES (?1, ?2, ?3, ?4, ?5)
             ON CONFLICT (book_id, location) DO UPDATE SET label = excluded.label",
            params![book_id, location, label, progress.clamp(0.0, 1.0), now()],
        )?;
        Ok(())
    }

    pub fn remove_bookmark(&self, id: i64) -> Result<()> {
        self.conn.execute("DELETE FROM bookmarks WHERE id = ?1", [id])?;
        Ok(())
    }

    pub fn clear_bookmarks(&self, book_id: i64) -> Result<()> {
        self.conn.execute("DELETE FROM bookmarks WHERE book_id = ?1", [book_id])?;
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Write;

    fn sample_pdf() -> String {
        let path = std::env::temp_dir().join("oer-library-test.pdf");
        std::fs::File::create(&path).unwrap().write_all(b"%PDF-1.4 test").unwrap();
        path.to_string_lossy().into_owned()
    }

    #[test]
    fn add_list_progress_remove() {
        let lib = Library::open_in_memory().unwrap();
        let pdf = sample_pdf();

        let res = lib.add_paths(&[pdf.clone(), pdf.clone(), "x.docx".into()]).unwrap();
        assert_eq!(res.added.len(), 1);
        assert_eq!(res.duplicates, vec![pdf]);
        assert_eq!(res.unsupported, vec!["x.docx".to_string()]);

        let id = res.added[0].id;
        assert_eq!(res.added[0].title, "oer-library-test");

        lib.update_metadata(id, Some("Real title"), Some("Someone"), None).unwrap();
        lib.save_progress(id, "3", 1.7).unwrap();
        let book = lib.get(id).unwrap();
        assert_eq!(book.title, "Real title");
        assert_eq!(book.location.as_deref(), Some("3"));
        assert_eq!(book.progress, 1.0);

        lib.remove(id).unwrap();
        assert!(lib.list().unwrap().is_empty());
    }

    #[test]
    fn bookmarks_are_unique_sorted_and_cascade() {
        let lib = Library::open_in_memory().unwrap();
        let id = lib.add_paths(&[sample_pdf()]).unwrap().added[0].id;

        lib.add_bookmark(id, "9", "Page 9", 0.9).unwrap();
        lib.add_bookmark(id, "2", "Page 2", 0.2).unwrap();
        lib.add_bookmark(id, "2", "Renamed", 0.2).unwrap();
        let marks = lib.bookmarks(id).unwrap();
        assert_eq!(marks.iter().map(|b| b.label.as_str()).collect::<Vec<_>>(), ["Renamed", "Page 9"]);

        lib.remove_bookmark(marks[0].id).unwrap();
        assert_eq!(lib.bookmarks(id).unwrap().len(), 1);

        lib.remove(id).unwrap();
        let orphans: i64 = lib.conn.query_row("SELECT COUNT(*) FROM bookmarks", [], |r| r.get(0)).unwrap();
        assert_eq!(orphans, 0);
    }
}
