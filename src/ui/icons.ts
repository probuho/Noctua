export type IconName = keyof typeof PATHS;

export function icon(name: IconName): SVGSVGElement {
  const wrap = document.createElement("span");
  wrap.innerHTML = `<svg class="icon-svg" viewBox="0 0 24 24" width="20" height="20" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${PATHS[name]}</svg>`;
  return wrap.firstElementChild as SVGSVGElement;
}

/** Replaces the icon inside a button (e.g. play/pause). */
export function setIcon(button: HTMLElement, name: IconName): void {
  button.querySelector(".icon-svg")?.replaceWith(icon(name));
}
