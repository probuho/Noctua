const strings: Strings = navigator.language.toLowerCase().startsWith("es") ? es : en;

export function t(key: keyof Strings, ...args: string[]): string {
  return args.reduce((s, arg, i) => s.replace(`%${i + 1}`, arg), strings[key]);
}
